"""
exp_ood_cifar.py
================
Demonstrates the Out-of-Distribution (OOD) detection capability 
of the KAN-EBM. Because it models the energy landscape E(x),
in-distribution samples (CIFAR-10) should have lower energy than
OOD samples (SVHN).

This is a zero-shot capability. No classifier or discriminator is trained.
"""

import sys
import argparse
from pathlib import Path

import torch
import numpy as np
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'src'))
sys.path.insert(0, str(ROOT / 'experiments'))


@torch.no_grad()
def compute_energies(model, loader, device, max_batches=20):
    model.eval()
    energies = []
    
    for i, (x_batch, _) in enumerate(loader):
        if i >= max_batches:
            break
        x_batch = x_batch.to(device)
        # Evaluate energy per image because model.energy sums over the batch
        for j in range(x_batch.size(0)):
            x_single = x_batch[j:j+1]
            e = model.energy(x_single).item()
            energies.append(e)
            
    return np.array(energies)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--device', default='auto')
    args = parser.parse_args()

    device = (torch.device('cuda') if torch.cuda.is_available() else torch.device('cpu')) \
             if args.device == 'auto' else torch.device(args.device)

    print(f"Device: {device}")

    # 1. Load trained KAN-EBM
    from exp_cifar10 import KANEnergyModel as CifarKANEBM
    kan_ckpt = ROOT / 'outputs' / 'cifar10' / 'kan_ebm_f32.pt'
    if not kan_ckpt.exists():
        print(f"Waiting for {kan_ckpt} to be generated by overnight run.")
        print("Using dummy fallback for testing script.")
        model_kan = CifarKANEBM(n_filters=32, filter_size=5, kan_hidden=[96, 16], n_channels=3).to(device)
    else:
        model_kan = CifarKANEBM(n_filters=32, filter_size=5, kan_hidden=[96, 16], n_channels=3).to(device)
        model_kan.load_state_dict(torch.load(kan_ckpt, map_location=device, weights_only=True))
        print("Loaded CIFAR-10 Base Checkpoint.")

    # 2. Load Datasets
    import torchvision
    import torchvision.transforms as T
    
    tf = T.Compose([
        T.Resize((32, 32)),
        T.ToTensor(), 
        T.Normalize((0.5, 0.5, 0.5), (0.5, 0.5, 0.5))
    ])
    
    # In-Distribution: CIFAR-10
    cifar_test = torchvision.datasets.CIFAR10(ROOT / 'data', train=False, download=True, transform=tf)
    cifar_loader = torch.utils.data.DataLoader(cifar_test, batch_size=128, shuffle=True)
    
    # Out-of-Distribution: SVHN
    svhn_test = torchvision.datasets.SVHN(ROOT / 'data', split='test', download=True, transform=tf)
    svhn_loader = torch.utils.data.DataLoader(svhn_test, batch_size=128, shuffle=True)
    
    print("\nComputing energy for In-Distribution (CIFAR-10)...")
    e_in = compute_energies(model_kan, cifar_loader, device)
    
    print("Computing energy for Out-of-Distribution (SVHN)...")
    e_out = compute_energies(model_kan, svhn_loader, device)
    
    # 3. Compute AUROC
    # Label 0 for IN, 1 for OUT.
    # We expect E_out > E_in, so the score is exactly the energy.
    y_true = np.concatenate([np.zeros(len(e_in)), np.ones(len(e_out))])
    y_scores = np.concatenate([e_in, e_out])
    
    auroc = roc_auc_score(y_true, y_scores)
    
    print(f"\n======================================")
    print(f"OOD Detection (CIFAR-10 vs SVHN)")
    print(f"AUROC: {auroc:.4f}")
    print(f"======================================")
    
    if auroc < 0.5:
        print("Note: If AUROC < 0.5, the model assigns lower energy to OOD data.")
        print("This is a known issue in deep generative models (e.g. Nalisnick et al. 2018).")

if __name__ == '__main__':
    main()
